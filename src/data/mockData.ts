import { HealthRecord, AgeGroup, Zone, RiskLevel, SmokingStatus, AlcoholStatus, ExerciseStatus, DietHabit, HealthStatistics } from '../types';

export function calculateBmiCategory(bmi: number): HealthRecord['bmiCategory'] {
  if (bmi < 18.5) return 'น้ำหนักน้อย';
  if (bmi < 23.0) return 'ปกติ';
  if (bmi < 25.0) return 'น้ำหนักเกิน (ท้วม)';
  if (bmi < 30.0) return 'อ้วนระดับ 1';
  return 'อ้วนอันตราย (ระดับ 2)';
}

export function calculateFbsStatus(fbs: number): HealthRecord['fbsStatus'] {
  if (fbs < 100) return 'ปกติ (<100)';
  if (fbs <= 125) return 'กลุ่มเสี่ยง (100-125)';
  return 'เสี่ยงสูง/เบาหวาน (≥126)';
}

export function calculateBpStatus(sys: number, dia: number): HealthRecord['bpStatus'] {
  if (sys < 120 && dia < 80) return 'ปกติ (<120/80)';
  if (sys < 140 && dia < 90) return 'เฝ้าระวัง (120-139/80-89)';
  return 'ความดันสูง (≥140/90)';
}

export function calculateCholesterolStatus(chol: number): HealthRecord['cholesterolStatus'] {
  if (chol < 200) return 'ปกติ (<200)';
  if (chol < 240) return 'ค่อนข้างสูง (200-239)';
  return 'สูง (≥240)';
}

export function getAgeGroup(age: number): AgeGroup {
  if (age <= 24) return '15-24 ปี (เยาวชน)';
  if (age <= 45) return '25-45 ปี (วัยทำงาน)';
  if (age <= 59) return '46-59 ปี (วัยกลางคน)';
  return '60 ปีขึ้นไป (ผู้สูงอายุ)';
}

export function calculateOverallRisk(
  bmiCat: string,
  fbsStatus: string,
  bpStatus: string,
  smoking: string,
  exercise: string
): RiskLevel {
  let riskScore = 0;
  if (fbsStatus.includes('เสี่ยงสูง')) riskScore += 3;
  else if (fbsStatus.includes('กลุ่มเสี่ยง')) riskScore += 1.5;

  if (bpStatus.includes('ความดันสูง')) riskScore += 3;
  else if (bpStatus.includes('เฝ้าระวัง')) riskScore += 1.5;

  if (bmiCat.includes('อ้วนอันตราย')) riskScore += 2.5;
  else if (bmiCat.includes('อ้วนระดับ 1')) riskScore += 1.5;
  else if (bmiCat.includes('น้ำหนักเกิน')) riskScore += 1;

  if (smoking === 'สูบเป็นประจำ') riskScore += 2;
  else if (smoking === 'สูบเป็นครั้งคราว') riskScore += 1;

  if (exercise === 'ไม่ออกกำลังกาย') riskScore += 1.5;

  if (riskScore >= 6) return 'เสี่ยงสูง';
  if (riskScore >= 3.5) return 'เสี่ยงปานกลาง';
  if (riskScore >= 1.5) return 'เสี่ยงต่ำ';
  return 'ปกติ';
}

