export function computeStatistics(records: HealthRecord[]): HealthStatistics {
  const totalCount = records.length;
  if (totalCount === 0) {
    return {
      totalCount: 0,
      avgBmi: 0,
      minBmi: 0,
      maxBmi: 0,
      avgFbs: 0,
      minFbs: 0,
      maxFbs: 0,
      avgSystolicBp: 0,
      minSystolicBp: 0,
      maxSystolicBp: 0,
      avgCholesterol: 0,
      highRiskCount: 0,
      highRiskPercentage: 0,
      overweightCount: 0,
      overweightPercentage: 0,
      genderRatio: { male: 0, female: 0, malePercent: 0, femalePercent: 0 },
      abnormalFbsCount: 0,
      abnormalFbsPercent: 0,
      hypertensionCount: 0,
      hypertensionPercent: 0,
    };
  }

  let sumBmi = 0;
  let minBmi = Infinity;
  let maxBmi = -Infinity;

  let sumFbs = 0;
  let minFbs = Infinity;
  let maxFbs = -Infinity;

  let sumSys = 0;
  let minSys = Infinity;
  let maxSys = -Infinity;

  let sumChol = 0;
  let highRiskCount = 0;
  let overweightCount = 0;
  let maleCount = 0;
  let femaleCount = 0;
  let abnormalFbsCount = 0;
  let hypertensionCount = 0;

  for (const r of records) {
    sumBmi += r.bmi;
    if (r.bmi < minBmi) minBmi = r.bmi;
    if (r.bmi > maxBmi) maxBmi = r.bmi;

    sumFbs += r.fbs;
    if (r.fbs < minFbs) minFbs = r.fbs;
    if (r.fbs > maxFbs) maxFbs = r.fbs;

    sumSys += r.systolicBp;
    if (r.systolicBp < minSys) minSys = r.systolicBp;
    if (r.systolicBp > maxSys) maxSys = r.systolicBp;

    sumChol += r.cholesterol;

    if (r.overallRisk === 'เสี่ยงสูง') highRiskCount++;
    if (r.bmi >= 23.0) overweightCount++;
    if (r.gender === 'ชาย') maleCount++;
    else femaleCount++;

    if (r.fbs >= 100) abnormalFbsCount++;
    if (r.systolicBp >= 140 || r.diastolicBp >= 90) hypertensionCount++;
  }

  return {
    totalCount,
    avgBmi: Number((sumBmi / totalCount).toFixed(1)),
    minBmi: Number(minBmi.toFixed(1)),
    maxBmi: Number(maxBmi.toFixed(1)),
    avgFbs: Math.round(sumFbs / totalCount),
    minFbs: Math.round(minFbs),
    maxFbs: Math.round(maxFbs),
    avgSystolicBp: Math.round(sumSys / totalCount),
    minSystolicBp: Math.round(minSys),
    maxSystolicBp: Math.round(maxSys),
    avgCholesterol: Math.round(sumChol / totalCount),
    highRiskCount,
    highRiskPercentage: Number(((highRiskCount / totalCount) * 100).toFixed(1)),
    overweightCount,
    overweightPercentage: Number(((overweightCount / totalCount) * 100).toFixed(1)),
    genderRatio: {
      male: maleCount,
      female: femaleCount,
      malePercent: Number(((maleCount / totalCount) * 100).toFixed(1)),
      femalePercent: Number(((femaleCount / totalCount) * 100).toFixed(1)),
    },
    abnormalFbsCount,
    abnormalFbsPercent: Number(((abnormalFbsCount / totalCount) * 100).toFixed(1)),
    hypertensionCount,
    hypertensionPercent: Number(((hypertensionCount / totalCount) * 100).toFixed(1)),
  };
}
